const DICTS = { nl, en };
let lang = "nl";
try {
  const stored = localStorage.getItem("dw.lang");
  if (stored && DICTS[stored]) lang = stored;
} catch { /* opslag niet beschikbaar */ }

export function setLang(l) {
  if (!DICTS[l]) return;
  lang = l;
  document.documentElement.lang = l;
  try { localStorage.setItem("dw.lang", l); } catch { /* */ }
}

export function getLang() { return lang; }

export function t(key, vars) {
  let s = (DICTS[lang] && DICTS[lang][key]) ?? nl[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
  return s;
}

/** Vertaal statische elementen met data-i18n / data-i18n-title / data-i18n-placeholder. */
export function translateDom(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
}
